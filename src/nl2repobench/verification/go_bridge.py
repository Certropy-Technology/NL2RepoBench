"""Typed Go JSON bridge IR and source generator for serializable APIs."""

from __future__ import annotations

import re
from typing import Literal, Self

from pydantic import Field, model_validator

from nl2repobench.domain.canonical_models import CanonicalRecord as RecordModel

GoValueType = Literal["string", "bool", "int64", "float64"]
_IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_IMPORT = re.compile(r"^[A-Za-z0-9][A-Za-z0-9./_-]*$")


class GoBridgeOperation(RecordModel):
    operation_id: str = Field(pattern=r"^[A-Za-z0-9._-]+$")
    import_path: str = Field(min_length=1)
    symbol: str = Field(min_length=1)
    argument_types: tuple[GoValueType, ...] = ()
    return_type: GoValueType
    returns_error: bool = False

    @model_validator(mode="after")
    def validate_identifiers(self) -> Self:
        if not _IMPORT.fullmatch(self.import_path) or not _IDENTIFIER.fullmatch(self.symbol):
            raise ValueError("Go bridge import path or symbol is invalid")
        return self


class GoBridgeSpec(RecordModel):
    module_path: str = Field(min_length=1)
    operations: tuple[GoBridgeOperation, ...] = Field(min_length=1)

    @model_validator(mode="after")
    def validate_operation_ids(self) -> Self:
        ids = [operation.operation_id for operation in self.operations]
        if len(set(ids)) != len(ids):
            raise ValueError("Go bridge operation IDs must be unique")
        return self


_GO_TYPES = {"string": "string", "bool": "bool", "int64": "int64", "float64": "float64"}


def generate_go_bridge(spec: GoBridgeSpec) -> str:
    """Generate a bridge containing only public API mappings and transport code."""

    imports = sorted({operation.import_path for operation in spec.operations})
    aliases = {path: f"pkg{index}" for index, path in enumerate(imports)}
    import_block = "\n".join(f'\t{alias} "{path}"' for path, alias in aliases.items())
    cases: list[str] = []
    for operation in spec.operations:
        args = []
        decode = []
        for index, argument_type in enumerate(operation.argument_types):
            name = f"arg{index}"
            go_type = _GO_TYPES[argument_type]
            args.append(name)
            decode.append(
                f"\tvar {name} {go_type}\n"
                f"\tif err := json.Unmarshal(request.Args[{index}], &{name}); err != nil {{\n"
                '\t\treturn response{ErrorType: "InvalidInput", Message: err.Error()}\n'
                "\t}"
            )
        call = f"{aliases[operation.import_path]}.{operation.symbol}({', '.join(args)})"
        if operation.returns_error:
            call_code = (
                f"\tvalue, callErr := {call}\n"
                '\tif callErr != nil {\n'
                '\t\treturn response{ErrorType: "CallFailed", Message: callErr.Error()}\n'
                "\t}\n"
            )
        else:
            call_code = f"\tvalue := {call}\n"
        cases.append(
            f'case "{operation.operation_id}":\n'
            + "\n".join(decode)
            + "\n"
            + call_code
            + "\tencoded, err := json.Marshal(value)\n"
            + '\tif err != nil {\n'
            + '\t\treturn response{ErrorType: "CallFailed", Message: err.Error()}\n'
            + "\t}\n\treturn response{Value: encoded}"
        )
    return f'''// Code generated by nl2repobench. DO NOT add hidden data here.
package main

import (
    "bufio"
    "encoding/json"
    "fmt"
    "os"
{import_block}
)

type request struct {{
    Operation string `json:"operation"`
    Args []json.RawMessage `json:"args"`
}}
type response struct {{
    Value json.RawMessage `json:"value,omitempty"`
    ErrorType string `json:"error_type,omitempty"`
    Message string `json:"message,omitempty"`
}}

func call(request request) response {{
    switch request.Operation {{
        {chr(10).join(cases)}
    default:
        return response{{ErrorType: "InvalidInput", Message: "unknown operation"}}
    }}
}}

func main() {{
    scanner := bufio.NewScanner(os.Stdin)
    scanner.Buffer(make([]byte, 4096), 256*1024)
    encoder := json.NewEncoder(os.Stdout)
    for scanner.Scan() {{
        var input request
        if err := json.Unmarshal(scanner.Bytes(), &input); err != nil {{
            _ = encoder.Encode(response{{ErrorType: "InvalidInput", Message: err.Error()}})
            continue
        }}
        if err := encoder.Encode(call(input)); err != nil {{
            fmt.Fprintln(os.Stderr, err)
            os.Exit(1)
        }}
    }}
    if err := scanner.Err(); err != nil {{ fmt.Fprintln(os.Stderr, err); os.Exit(1) }}
}}
'''


__all__ = ["GoBridgeOperation", "GoBridgeSpec", "generate_go_bridge"]
